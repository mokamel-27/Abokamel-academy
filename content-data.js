// يجيب باب معين من مادة
function getChapter(subjectId, chapterId) {
  const subject = getSubject(subjectId);
  if (!subject) return null;
  return subject.chapters.find(function (c) { return c.id === Number(chapterId); });
}

// بيبني امتحان شامل من كل أبواب المادة (بياخد أول سؤالين من كل باب)
function buildFinalExam(subjectId) {
  const subject = getSubject(subjectId);
  if (!subject) return [];
  let questions = [];
  subject.chapters.forEach(function (ch) {
    const picked = ch.chapterQuiz.slice(0, 2).map(function (q) {
      return Object.assign({}, q, { fromChapter: ch.id, chapterTitle: ch.title });
    });
    questions = questions.concat(picked);
  });
  return questions;
}
